ANNOTATIONS: list[dict[str, Any]] = [dict(row) for row in CLASSICS_ANNOTATIONS
                                      if row["source"] == SOURCE]
_covered: list[set[int]] = [set() for _ in _PARAGRAPHS]


def _nth(text: str, needle: str, occurrence: int) -> int:
    cursor = 0
    for _ in range(occurrence + 1):
        index = text.index(needle, cursor)
        cursor = index + len(needle)
    return index


def _positions(row: dict[str, Any]) -> set[int]:
    start = _nth(_PARAGRAPHS[row["paragraph_index"]], row["anchor"],
                 row.get("anchor_occurrence", 0))
    start += _nth(row["anchor"], row["token"], row.get("token_occurrence", 0))
    return set(range(start, start + len(row["token"])))


for _row in ANNOTATIONS:
    _covered[_row["paragraph_index"]].update(_positions(_row))


def _add(paragraph_index: int, anchor: str, rows: list[tuple[str, ...]]) -> None:
    cursor = 0
    for row in rows:
        token, sense_key, meaning, part_of_speech, reasoning, *flags = row
        start = anchor.index(token, cursor)
        if any(char.isalnum() for char in anchor[cursor:start]):
            raise ValueError(f"Unglossed text before {token!r}: {anchor!r}")
        entry = {
            "source": SOURCE, "paragraph_index": paragraph_index,
            "anchor": anchor, "anchor_occurrence": 0,
            "token": token, "token_occurrence": anchor[:start].count(token),
            "sense_key": sense_key, "meaning": meaning,
            "part_of_speech": part_of_speech,
            "variability": flags[0] if flags else "CONTEXTUAL",
            "reasoning": reasoning,
        }
        positions = _positions(entry)
        if not positions <= _covered[paragraph_index]:
            ANNOTATIONS.append(entry)
            _covered[paragraph_index].update(positions)
        cursor = start + len(token)
    if any(char.isalnum() for char in anchor[cursor:]):
        raise ValueError(f"Unglossed ending: {anchor!r}")


