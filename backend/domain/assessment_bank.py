"""Independent, unreviewed assessment candidates, not calibrated exam items.

All passages are exact continuous spans of the currently stored public-domain
edition. Chapter tasks include the complete declared FULL/CHAPTER reading unit.
Answer identities are stable IDs, never presentation letters or array indices.
"""
from __future__ import annotations

from .reading_context import reading_context_for

# v1 was already frozen in the local revision store during parallel integration.
# Refined distractors are a new version, never a rewrite of that stored edition.
BANK_VERSION = "assessment-pilot-v2"
QUESTION_BANK: list[dict] = []


def _q(dimension: str, difficulty: str, number: int, source: str,
       passage: str | None, stem: str, correct: str, wrong: tuple[str, str, str],
       explanation: str, *tags: str) -> None:
    context = reading_context_for({"source": source, "passage": ""})
    full_text = context["full_text"]
    text = full_text if passage is None else passage
    if not text or text not in full_text:
        raise ValueError(f"Non-continuous assessment passage: {source}: {text}")
    if dimension == "chapter" and (context["extent"] not in ("FULL", "CHAPTER") or text != full_text):
        raise ValueError("Chapter questions require the entire declared reading unit")
    identifier = f"{dimension}-{difficulty.lower()}-{number:02d}"
    # Spread authored answer positions as well as runtime presentation order.
    correct_index = (number - 1 + ("vocabulary", "syntax", "context", "chapter").index(dimension)) % 4
    texts = list(wrong)
    texts.insert(correct_index, correct)
    options = [{"id": f"{identifier}-option-{i + 1}", "text": option} for i, option in enumerate(texts)]
    paragraph_index = next((p for p, paragraph in enumerate(context["paragraphs"]) if text in paragraph), None)
    start = context["paragraphs"][paragraph_index].index(text) if paragraph_index is not None else None
    QUESTION_BANK.append({
        "id": identifier, "version": BANK_VERSION, "dimension": dimension,
        "difficulty": difficulty, "type": "choice", "stem": stem,
        "source": source, "source_url": context["source_url"], "passage": text,
        "options": options, "answer_id": options[correct_index]["id"],
        "explanation": explanation, "tags": list(tags),
        "review_status": "DRAFT", "reviewer": None, "reviewed_at": None,
        "material_extent": context["extent"], "passage_extent": context["extent"] if text == full_text else "EXCERPT",
        "text_version": context["text_version"], "paragraph_index": paragraph_index,
        "start": start, "end": start + len(text) if start is not None else None,
        "full_text_start": full_text.index(text), "full_text_end": full_text.index(text) + len(text),
    })


