async (page) => {
  const assert = (value, label) => { if (!value) throw new Error(label) }
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const endpoint = 'http://127.0.0.1:8001/api/v1/admin/assessment/questions/chapter-l1-01'
  const current = () => page.request.get(endpoint).then(response => response.json())
  const before = await current()
  assert(before.version === 0 && before.validation_valid === true, 'Fresh isolated revision')
  assert(await page.getByRole('textbox', { name: '题干', exact: true }).inputValue() === before.question.stem, 'Real frozen text')
  for (const width of [1440, 820, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    await page.getByRole('heading', { name: '篇章理解 · L1', exact: true }).scrollIntoViewIfNeeded()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), `No overflow ${width}`)
    await page.screenshot({ path: `output/playwright/assessment-editorial-${width}.png` })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1440, height: 900 })
  const stem = page.getByRole('textbox', { name: '题干', exact: true })
  await stem.fill(before.question.stem + '【隔离回归校订】')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '课程与来源', exact: true }).click()
  assert(await stem.isVisible(), 'Unsaved tab change cancelled')
  await page.getByRole('textbox', { name: '本次编辑／审核人', exact: true }).fill('隔离测试，不是真实教研')
  await page.getByRole('textbox', { name: '本次核验依据／修改说明', exact: true }).fill('只核验事务与响应恢复，不认证内容。')
  const pattern = '**/api/v1/admin/assessment/questions/chapter-l1-01'
  let dropped = false
  const loseResponse = async route => {
    if (route.request().method() !== 'PATCH') return route.fallback()
    await route.fetch({ url: endpoint }); dropped = true; await route.abort()
  }
  await page.route(pattern, loseResponse)
  await page.getByRole('button', { name: '保存草稿新版本', exact: true }).click()
  const recover = page.getByRole('button', { name: '使用原提交标识恢复结果', exact: true })
  await recover.waitFor()
  assert(dropped && (await current()).version === 1, 'Lost response actually committed in isolated DB')
  assert(await page.getByRole('button', { name: '审核通过当前版本', exact: true }).isDisabled(), 'Unknown response blocks other writes')
  const pendingBefore = await page.evaluate(() => JSON.parse(sessionStorage.getItem('wenyan-assessment-editorial-pending-v1')))
  await page.unroute(pattern, loseResponse)
  await page.reload()
  await page.getByRole('button', { name: '评测题审核', exact: true }).click()
  const pendingAfter = await page.evaluate(() => JSON.parse(sessionStorage.getItem('wenyan-assessment-editorial-pending-v1')))
  assert(pendingBefore.key === pendingAfter.key && JSON.stringify(pendingBefore.body) === JSON.stringify(pendingAfter.body), 'Reload retains original key and body')
  await page.getByRole('button', { name: '使用原提交标识恢复结果', exact: true }).click()
  await page.getByText('草稿新版本已保存，原审核失效，须重新人工核对。旧试卷不被覆盖。', { exact: true }).waitFor()
  assert((await current()).version === 1, 'Recovery never duplicates revision')
  const sign = async () => {
    await page.getByRole('textbox', { name: '本次编辑／审核人', exact: true }).fill('隔离测试，不是真实教研')
    await page.getByRole('textbox', { name: '本次核验依据／修改说明', exact: true }).fill('只验证状态流转，不能迁移为真实审核。')
  }
  await sign(); page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '审核通过当前版本', exact: true }).click()
  await page.getByText('已记录当前版本的人工署名审核。署名未经登录认证；不代表题库已完成正式分级校准。', { exact: true }).waitFor()
  assert((await current()).question.review_status === 'APPROVED', 'Isolated approval')
  await sign(); page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '退回当前版本', exact: true }).click()
  await page.getByText('当前版本已退回，退回依据已保留。后续修改后须重新审核。', { exact: true }).waitFor()
  assert((await current()).question.review_status === 'REJECTED', 'Isolated rejection')
  await stem.fill(before.question.stem + '【隔离重新校订】'); await sign()
  await page.getByRole('button', { name: '保存草稿新版本', exact: true }).click()
  await page.getByText('草稿新版本已保存，原审核失效，须重新人工核对。旧试卷不被覆盖。', { exact: true }).waitFor()
  assert((await current()).question.review_status === 'DRAFT', 'Re-edit clears approval and rejection')
  const history = page.getByText('修订与审核历史 · 6 条', { exact: true })
  await history.focus(); await page.keyboard.press('Enter')
  assert(await history.evaluate(node => node.parentElement.open), 'Keyboard history accessible')
  const badList = '**/api/v1/admin/assessment/questions?*'
  await page.route(badList, route => route.fulfill({ status: 500, contentType: 'application/json', body: '{"error":{"code":"QA_SERVER_FAILURE"}}' }))
  await page.getByRole('button', { name: '重新读取候选题列表', exact: true }).click()
  await page.getByText('QA_SERVER_FAILURE', { exact: true }).waitFor()
  assert(await page.locator('.annotation-list button').count() === 0, 'Failed list hides stale data')
  await page.unroute(badList)
  await page.getByRole('button', { name: '重新读取候选题列表', exact: true }).click()
  await page.getByText('48 道候选题 · 第 1–12 道', { exact: true }).waitFor()
  assert(errors.length === 0, `Browser errors ${errors.join(';')}`)
  console.log('EDITORIAL_FOUR_WIDTHS_DIRTY_GUARD_LOST_RESPONSE_REFRESH_SAME_KEY_APPROVE_REJECT_REEDIT_KEYBOARD_500_RECOVERY_OK')
}
